"""Write video/hf/film.yaml from video/hf/SCRIPT.md, so the script's wording is the only copy of the words.

    python video/scripts/film_from_script.py        # then: python video/scripts/film_build.py

SCRIPT.md has one "### <n> · <title>" section per beat; every "**X:** words" line is spoken by speaker X (N narrator,
A Atlas, H Hemdutt, I Ilan, D Dominick, X Xander, T the trainee). [Brackets], HTML comments and *(italic notes)* are
not spoken. BEATS below gives each beat its scene id, its chapter title and its action time: `lead` seconds before the
first line and `hold` seconds of silence after a given line (the moments that are action, not words).
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "hf" / "SCRIPT.md"
FILM = ROOT / "hf" / "film.yaml"

# beat number -> (scene id, chapter title, lead seconds, {line index: hold seconds})
BEATS = {
    0: ("problem", "A dozen apps", 1.0, {}),
    1: ("intro", "Atlas", 2.0, {}),
    2: ("morning", "Good morning", 1.0, {1: 0.5, 7: 1.0, 9: 1.5}),
    3: ("sources", "What fed the brief", 1.0, {}),
    4: ("model", "The model on the box", 1.0, {}),
    5: ("desk", "At the desk", 1.0, {2: 1.0}),
    6: ("faces", "Faces", 1.0, {}),
    7: ("kitchen", "The kitchen", 1.5, {0: 1.5}),
    # 8 (the Sort It round) was cut by Dom, Sun 5:05 AM.
    9: ("sorttech", "What the kitchen camera runs on", 1.0, {}),
    10: ("lab", "The learning lab", 1.0, {}),
    11: ("device", "On the device", 1.0, {}),
    12: ("league", "Friends", 1.0, {0: 1.5, 2: 0.5}),
    13: ("friends", "How the boxes talk", 1.0, {}),
    14: ("lives", "Same box, other lives", 1.0, {}),
    15: ("plant", "Same engine, different data", 1.0, {}),
    16: ("shift", "Xander's shift", 0.5, {2: 1.5, 4: 0.8, 5: 1.2}),
    17: ("end", "Atlas", 0.0, {0: 2.0}),
}

HEAD = {
    "rate": "+30%",  # Dom, Sun 4:20 AM: every voice at 1.3x
    "voices": {
        "N": "en-US-AndrewMultilingualNeural",
        "A": "en-US-GuyNeural",  # until Piper en_US-ryan-medium (the box's own voice) is installed here
        "H": "en-US-BrianMultilingualNeural",
        "I": "en-US-ChristopherNeural",
        "D": "en-US-EricNeural",
        "X": "en-US-RogerNeural",
        "T": "en-US-SteffanNeural",
    },
    "names": {"N": "", "A": "Atlas", "H": "Hemdutt", "I": "Ilan", "D": "Dominick", "X": "Xander", "T": "Trainee"},
    "gap_s": 0.3,
    "pad_s": 0.3,
    "tail_s": 0.7,
}

LINE = re.compile(r"\*\*([A-Z])[^*]*?\*\*(?:\s*\([^)]*\))?:?\s*(.*?)(?=\s*·\s*\*\*[A-Z]|\n\*\*[A-Z]|\Z)", re.S)


def parse(text: str) -> dict[int, list[tuple[str, str]]]:
    body = text.split("\n---\n")[1]
    beats = {}
    for b in re.split(r"^### ", body, flags=re.M)[1:]:
        num = int(b.split(" ", 1)[0])
        b = re.sub(r"<!--.*?-->", "", b, flags=re.S)
        b = re.sub(r"\[[^\]]*\]", "", b, flags=re.S)
        b = re.sub(r"^\*\(.*?\)\*$", "", b, flags=re.M)
        beats[num] = [(m.group(1), " ".join(m.group(2).split()).strip(" ·")) for m in LINE.finditer(b) if m.group(2).strip(" ·\n")]
    return beats


def main() -> int:
    beats = parse(SCRIPT.read_text(encoding="utf-8"))
    if sorted(beats) != sorted(BEATS):
        print(f"SCRIPT.md beats {sorted(beats)} do not match BEATS {sorted(BEATS)}")
        return 1
    scenes = []
    for num in sorted(beats):
        sid, title, lead, holds = BEATS[num]
        lines = []
        for i, (who, said) in enumerate(beats[num]):
            line = {"who": who, "text": said}
            if holds.get(i):
                line["hold"] = holds[i]
            lines.append(line)
        sc = {"id": sid, "title": title, "beat": num, "lines": lines}
        if lead:
            sc["lead_s"] = lead
        scenes.append(sc)
    head = "# GENERATED by video/scripts/film_from_script.py from video/hf/SCRIPT.md. Change the words there.\n"
    FILM.write_text(head + yaml.safe_dump({**HEAD, "scenes": scenes}, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
    print(f"wrote {FILM.relative_to(ROOT.parent)}: {len(scenes)} scenes, {sum(len(s['lines']) for s in scenes)} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
