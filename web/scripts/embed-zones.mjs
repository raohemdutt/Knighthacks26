#!/usr/bin/env node
// Writes lib/zones.generated.ts from ../config/zones.yaml.
//
// The gateway has no endpoint that returns the zone polygons, so the Room map
// embeds them at build time (`npm run build` runs this first). It reads only the
// shape that file has today:
//
//   cam-door:
//     door: [[0.55, 0.55], [0.95, 0.55], ...]
//
// and stops with an error on anything else rather than guess. When
// config/zones.yaml is not there (a build outside the repo) the committed
// lib/zones.generated.ts is left as it is.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../config/zones.yaml");
const target = resolve(here, "../lib/zones.generated.ts");

if (!existsSync(source)) {
  console.log(`embed-zones: ${source} not found; keeping the committed lib/zones.generated.ts`);
  process.exit(0);
}

const stop = (n, line, why) => {
  console.error(`embed-zones: config/zones.yaml line ${n}: ${why}\n    ${line}`);
  process.exit(1);
};

const cameras = {};
let camera = null;
readFileSync(source, "utf8")
  .split("\n")
  .forEach((raw, i) => {
    const line = raw.replace(/\s+#.*$/, "").replace(/^#.*$/, "").trimEnd();
    if (!line.trim()) return;
    const cam = /^([A-Za-z0-9_-]+):$/.exec(line);
    if (cam) {
      camera = cam[1];
      cameras[camera] = {};
      return;
    }
    const zone = /^\s+([A-Za-z0-9_-]+):\s*(\[.*\])$/.exec(line);
    if (!zone || !camera) stop(i + 1, raw, "expected `camera:` or `  zone: [[x, y], ...]`");
    let polygon;
    try {
      polygon = JSON.parse(zone[2]);
    } catch {
      stop(i + 1, raw, "the polygon is not a list of [x, y] pairs");
    }
    const ok = Array.isArray(polygon) && polygon.length >= 3 && polygon.every((p) => Array.isArray(p) && p.length === 2 && p.every((v) => typeof v === "number" && v >= 0 && v <= 1));
    if (!ok) stop(i + 1, raw, "a polygon needs at least three [x, y] points between 0 and 1");
    cameras[camera][zone[1]] = polygon;
  });

if (!Object.keys(cameras).length) stop(1, "", "no cameras found");

const body = `/**
 * GENERATED by scripts/embed-zones.mjs from config/zones.yaml. Do not edit by hand.
 *
 * EMBEDDED AT BUILD TIME because the gateway has no endpoint that returns the
 * zone polygons. Replace this file with a fetch once one exists
 * (for example GET /api/zones).
 *
 * Polygons are in each camera's own image, normalized to 0..1 with (0, 0) at
 * the top left. They are not floor coordinates and the cameras are not placed
 * relative to each other.
 */

export type ZonePolygon = [number, number][];

export const ZONES: Record<string, Record<string, ZonePolygon>> = ${JSON.stringify(cameras, null, 2)};
`;

const before = existsSync(target) ? readFileSync(target, "utf8") : "";
if (before !== body) writeFileSync(target, body);
const count = Object.values(cameras).reduce((n, z) => n + Object.keys(z).length, 0);
console.log(`embed-zones: ${count} zones from ${Object.keys(cameras).length} cameras${before === body ? " (unchanged)" : ""}`);
